package com.lagradost.cloudstream3.ui.result

/**
 * JVM stubs for CS3 app-level UI result classes.
 *
 * Some plugins reference these app-level classes (e.g. to register custom
 * episode UI components). On JVM desktop we don't have the app-level UI —
 * these stubs exist only so plugin bytecode can link.
 */

/** Stub for CS3's ResultEpisode — used by some plugins to build episode data. */
open class ResultEpisode

/** Stub for CS3's LinkLoadingResult — used by some plugins during link loading. */
open class LinkLoadingResult

/** Stub for CS3's ResultLoadingResult — used by some plugins. */
open class ResultLoadingResult
